/**
 * records.js (25.10.2026): the cut list record shape every engine writes
 * (sash, casement, door, partition), moved out of calculations.js so a new
 * engine module can import it without a circular import. A pure move: the
 * record keys and the rounding are exactly those of calculations.js.
 */

export function parseSection(section) {
    if (!section) return { width: null, height: null };
    const normalised = section.replace(/×/g, 'x');
    const parts = normalised.split('x').map((value) => Number(value.trim()));
    return { width: parts[0] ?? null, height: parts[1] ?? null };
}

export function round(value) {
    return Math.round((Number(value) + Number.EPSILON) * 100) / 100;
}

export function createComponentRecord(windowSpec, group, elementName, section, length, quantity = 1, notes = '') {
    const sectionInfo = parseSection(section);
    return {
        windowId: windowSpec.id,
        windowName: windowSpec.name,
        group,
        elementName,
        section,
        sizeLabel: section,
        finishedWidth: sectionInfo.height ?? sectionInfo.width ?? null,
        thickness: sectionInfo.width ?? null,
        length: round(length),
        quantity,
        notes,
    };
}
